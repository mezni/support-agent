from datetime import datetime
from typing import Optional, List, Dict, Any, Literal
from pydantic import BaseModel, Field, EmailStr

# --- Chat & Agent Interaction Schemas ---

class AgentChatRequest(BaseModel):
    user_message: str = Field(..., description="The message from the customer or support representative.", min_length=1)
    customer_id: str = Field(..., description="Verified customer ID associated with the session.")
    chat_history: Optional[List[Dict[str, Any]]] = Field(default=[], description="Previous conversation turns for context.")


class AgentChatResponse(BaseModel):
    success: bool = Field(..., description="Indicates whether the agent turn executed successfully.")
    response: str = Field(..., description="The final text response generated by the AI agent.")


# --- Customer & Order Data Schemas ---

class CustomerProfileResponse(BaseModel):
    customer_id: str
    email: EmailStr
    full_name: str
    tier: str
    created_at: str


class OrderItemSchema(BaseModel):
    order_id: str
    status: str
    total_amount: float
    currency: str = "USD"
    created_at: str


# --- Refund & Return Request Schemas ---

class RefundEligibilityRequest(BaseModel):
    order_id: str = Field(..., description="The unique order ID to evaluate.")
    amount: float = Field(..., gt=0, description="The requested refund amount.")


class ReturnRequestCreate(BaseModel):
    order_id: str = Field(..., description="The unique order ID for the return.")
    customer_id: str = Field(..., description="The customer ID initiating the return.")
    reason: str = Field(..., description="Reason for the return request.", min_length=3)
    idempotency_key: str = Field(..., description="Unique idempotency key to prevent duplicate requests.")


class RefundIssueRequest(BaseModel):
    order_id: str = Field(..., description="The unique order ID for the refund.")
    customer_id: str = Field(..., description="The customer ID requesting the refund.")
    amount: float = Field(..., gt=0, description="The refund amount.")
    reason: str = Field(..., description="Reason for the refund.", min_length=3)
    idempotency_key: str = Field(..., description="Unique idempotency key for financial write safety.")


class RefundStatusResponse(BaseModel):
    success: bool = True
    refund_id: str
    order_id: str
    customer_id: str
    amount: float
    currency: str
    status: Literal["PENDING_APPROVAL", "APPROVED", "REJECTED", "PROCESSING", "COMPLETED", "FAILED"]
    supervisor_id: Optional[str] = None
    created_at: str
    updated_at: str


class SupervisorDecisionRequest(BaseModel):
    decision: Literal["APPROVED", "REJECTED"] = Field(..., description="Supervisor decision outcome.")
    supervisor_id: str = Field(..., description="Unique identifier of the reviewing supervisor.")
    notes: Optional[str] = Field(None, description="Optional supervisor notes or justification.")


class SupervisorDecisionResponse(BaseModel):
    success: bool = True
    refund_id: str
    status: str
    message: str
